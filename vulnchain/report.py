"""VAPT report rendering: Markdown, HTML and JSON."""

import html
import json
from datetime import datetime, timezone

from .findings import SEVERITY_ORDER


def _counts(findings):
    counts = {sev: 0 for sev in SEVERITY_ORDER}
    for f in findings:
        counts[f.severity] = counts.get(f.severity, 0) + 1
    return counts


def render_markdown(scope, findings, chains, started, finished):
    counts = _counts(findings)
    lines = []
    lines.append(f"# Vulnerability Assessment Report: {scope.name}")
    lines.append("")
    lines.append(f"- Date: {finished:%Y-%m-%d %H:%M UTC}")
    lines.append(f"- Duration: {(finished - started).seconds}s")
    lines.append(f"- Scope: hosts {', '.join(scope.allowed_hosts)}; "
                 f"ports {', '.join(map(str, scope.allowed_ports))}")
    lines.append(f"- Tool: VulnChain (automated assessment with attack-chain correlation)")
    lines.append("")
    lines.append("## Executive summary")
    lines.append("")
    lines.append("| Severity | Count |")
    lines.append("|---|---|")
    for sev in reversed(SEVERITY_ORDER):
        lines.append(f"| {sev.capitalize()} | {counts[sev]} |")
    lines.append("")
    if chains:
        lines.append(f"**{len(chains)} attack chain(s) identified** - see the chains "
                     "section for how individual weaknesses compose into one path. "
                     "Chain severity is internal and equals the strongest demonstrated "
                     "impact, with no automatic amplification.")
        lines.append("")
    lines.append("## Methodology")
    lines.append("")
    lines.append("1. Scope validation - every request checked against the authorized scope file.")
    lines.append("2. Port and service discovery (TCP connect, in-scope ports only).")
    lines.append("3. HTTP reconnaissance - banners, security headers, allowed methods.")
    lines.append("4. Directory and sensitive-file enumeration (curated wordlist).")
    lines.append("5. TLS configuration review (certificate, protocol versions) where applicable.")
    lines.append("6. Credential verification - only when scope opts in and the target is a local lab.")
    lines.append("7. Attack-chain correlation and risk assessment.")
    lines.append("")
    if chains:
        lines.append("## Attack chains")
        lines.append("")
        for i, chain in enumerate(chains, 1):
            flag = " (verified in lab)" if chain["verified"] else ""
            lines.append(f"### Chain {i}: {chain['title']} - {chain['severity'].capitalize()}{flag}")
            lines.append("")
            lines.append(chain["narrative"])
            lines.append("")
            lines.append(f"Linked findings: {', '.join(chain['finding_ids'])}")
            lines.append("")
    lines.append("## Findings")
    lines.append("")
    ordered = sorted(findings, key=lambda f: -SEVERITY_ORDER.index(f.severity))
    for f in ordered:
        mark = " [verified]" if f.verified else ""
        lines.append(f"### {f.id}: {f.title}{mark}")
        lines.append("")
        lines.append(f"- Severity: {f.severity_display}")
        lines.append(f"- Target: {f.target}")
        lines.append(f"- Evidence: {f.evidence}")
        lines.append(f"- Remediation: {f.remediation}")
        lines.append("")
    lines.append("## Limitations")
    lines.append("")
    lines.append("- Automated checks cover reconnaissance and assessment; exploitation and "
                 "privilege escalation remain manual, authorized activities.")
    lines.append("- No CVE feed is bundled; version findings are not matched to known exploits.")
    lines.append("- Results reflect the target at test time and the configured wordlist and ports.")
    lines.append("- Banner and version findings reflect what the target presents; a lab, proxy "
                 "or honeypot can simulate banners (the bundled demo lab does exactly that).")
    lines.append("- Methods reported as 'advertised' come from an OPTIONS Allow header only; "
                 "they were not executed. 'Verified' items were confirmed with controls.")
    lines.append("")
    return "\n".join(lines)


def render_html(scope, findings, chains, started, finished):
    md_safe = html.escape(render_markdown(scope, findings, chains, started, finished))
    body = []
    counts = _counts(findings)
    body.append(f"<h1>Vulnerability Assessment Report: {html.escape(scope.name)}</h1>")
    body.append(f"<p class=meta>{finished:%Y-%m-%d %H:%M UTC} - generated by VulnChain</p>")
    body.append("<table><tr>" + "".join(f"<th>{s.capitalize()}</th>" for s in reversed(SEVERITY_ORDER)) + "</tr>")
    body.append("<tr>" + "".join(f"<td class='{s}'>{counts[s]}</td>" for s in reversed(SEVERITY_ORDER)) + "</tr></table>")
    if chains:
        body.append("<h2>Attack chains</h2>")
        for chain in chains:
            flag = " <span class=verified>verified in lab</span>" if chain["verified"] else ""
            body.append(f"<div class='chain {chain['severity']}'><h3>{html.escape(chain['title'])}"
                        f" - {chain['severity'].capitalize()}{flag}</h3>"
                        f"<p>{html.escape(chain['narrative'])}</p></div>")
    body.append("<h2>Findings</h2>")
    ordered = sorted(findings, key=lambda f: -SEVERITY_ORDER.index(f.severity))
    for f in ordered:
        mark = " <span class=verified>verified</span>" if f.verified else ""
        body.append(
            f"<div class='finding {f.severity}'><h3>{html.escape(f.id)}: "
            f"{html.escape(f.title)}{mark}</h3>"
            f"<p><b>Severity:</b> {html.escape(f.severity_display)}<br>"
            f"<b>Target:</b> {html.escape(f.target)}<br>"
            f"<b>Evidence:</b> {html.escape(f.evidence)}<br>"
            f"<b>Remediation:</b> {html.escape(f.remediation)}</p></div>")
    style = (
        "body{font-family:system-ui,sans-serif;max-width:900px;margin:2rem auto;padding:0 1rem}"
        "table{border-collapse:collapse}td,th{border:1px solid #ccc;padding:4px 12px;text-align:center}"
        ".finding,.chain{border-left:4px solid #999;padding:0 12px;margin:12px 0}"
        ".critical{border-color:#8b0000}.high{border-color:#d32f2f}.medium{border-color:#f57c00}"
        ".low{border-color:#fbc02d}.info{border-color:#9e9e9e}"
        ".verified{background:#e8f5e9;padding:1px 6px;border-radius:4px;font-size:0.85em}"
        ".meta{color:#666}")
    return (f"<!doctype html><html><head><meta charset=utf-8>"
            f"<title>VAPT report - {html.escape(scope.name)}</title>"
            f"<style>{style}</style></head><body>{''.join(body)}"
            f"<h2>Raw Markdown</h2><pre>{md_safe}</pre></body></html>")


def render_json(scope, findings, chains, started, finished):
    return json.dumps({
        "scope": scope.name,
        "generated_at": finished.isoformat(),
        "duration_seconds": (finished - started).seconds,
        "counts": _counts(findings),
        "chains": chains,
        "findings": [f.to_dict() for f in findings],
    }, indent=2)
